#!/usr/bin/env node
// SEO + GEO growth pages for withicons.com (owner: alternatives agent).
//   site/alternatives/index.html + site/alternatives/<library>.html   honest, sourced comparisons + migration guides
//   site/free/index.html + site/free/<topic>.html                      "free icons for …" landers with real icon grids
//   site/data/alternatives.json                                        page list for site-seo (llms.txt / sitemap)
// Static HTML rendered from the real icon data. Facts about other libraries live in site-alternatives/libraries.mjs,
// each with a source URL and the date it was checked.
// Usage: node forge/tools/site-alternatives.mjs
import fs from 'fs'
import { SITE } from './site-pages/lib.mjs'
import { buildFree } from './site-alternatives/free.mjs'
import { buildAlternatives } from './site-alternatives/alternatives.mjs'
import { LIBS } from './site-alternatives/libraries.mjs'
import { CHECKED } from './site-alternatives/render.mjs'

const alternatives = buildAlternatives()
const free = buildFree(LIBS)
const data = {
  generated: CHECKED,
  note: 'Pages generated by forge/tools/site-alternatives.mjs. Facts about other icon libraries were checked on the date shown and link to their official sources.',
  sections: [
    { id: 'alternatives', title: 'Icon library alternatives & comparisons', pages: alternatives },
    { id: 'free', title: 'Free icons by app, format, style and motion', pages: free },
  ],
}
fs.writeFileSync(SITE + '/data/alternatives.json', JSON.stringify(data, null, 2) + '\n')
console.log(`site-alternatives: ${alternatives.length} alternatives pages + ${free.length} free-icon pages, data/alternatives.json`)
